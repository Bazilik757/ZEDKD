def form_path(form_no: int) -> str:
    return f"form_{form_no}"


def load_form_rows(form_no: int) -> List[Dict[str, Any]]:
    return safe_load_data(form_path(form_no), [])


def save_form_rows(form_no: int, rows: List[Dict[str, Any]]):
    safe_save_data(form_path(form_no), rows)


def append_form_row(form_no: int, row: dict):
    rows = load_form_rows(form_no)
    rows.append(row)
    save_form_rows(form_no, rows)


def update_form_rows(
    form_no: int, predicate: Callable[[Dict[str, Any]], bool], updater: Callable[[Dict[str, Any]], None]
) -> int:
    rows = load_form_rows(form_no)
    changed = 0
    for row in rows:
        if predicate(row):
            updater(row)
            changed += 1
    if changed:
        save_form_rows(form_no, rows)
    return changed


def upsert_form_row(form_no: int, predicate: Callable[[Dict[str, Any]], bool], new_row: Dict[str, Any]) -> None:
    rows = load_form_rows(form_no)
    for row in rows:
        if predicate(row):
            row.update(new_row)
            save_form_rows(form_no, rows)
            return
    rows.append(new_row)
    save_form_rows(form_no, rows)
